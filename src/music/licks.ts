// A harmony lick, bar by bar: [chord, [[semi, beats], …], chord length in beats].
// Each bar's notes must fill it exactly, so the first note of every bar lands
// on the chord change.
export type Bar = [ChordKey, [number, number][], number?];

export function H(id: string, stage: number, home: Mode, bars: Bar[], tag?: string, lead = 0): Lick {
  const notes: number[] = [];
  const durs: number[] = [];
  const noteChord: number[] = [];
  const changes: Chord[] = bars.map(([key, ns, beats = 4], bi) => {
    const sum = ns.reduce((a, [, d]) => a + d, 0) + (bi === 0 ? lead : 0);
    if (Math.abs(sum - beats) > 1e-6) throw new Error(`lick ${id}: bar ${bi + 1} has ${sum} beats, expected ${beats}`);
    ns.forEach(([n, d]) => {
      notes.push(n);
      durs.push(d);
      noteChord.push(bi);
    });
    return { ...CH[key], beats };
  });
  return { id, stage, home, scale: scaleFromTag(tag) ?? home, notes, durs, tag, swing: SWING_STAGES.has(stage) || swingFromTag(tag), changes, noteChord, lead: lead || undefined };
}

// A harmony lick with its own chords (not from CH), e.g. from a transcription.
export function HC(
  id: string,
  stage: number,
  home: Mode,
  bars: { chord: Omit<Chord, 'beats'>; notes: [number, number][] }[],
  tag: string,
  swing: boolean,
  lead = 0,
): Lick {
  const notes: number[] = [];
  const durs: number[] = [];
  const noteChord: number[] = [];
  const changes: Chord[] = bars.map((b, bi) => {
    b.notes.forEach(([n, d]) => {
      notes.push(n);
      durs.push(d);
      noteChord.push(bi);
    });
    return { ...b.chord, beats: b.notes.reduce((a, [, d]) => a + d, 0) + (bi === 0 ? lead : 0) };
  });
  return { id, stage, home, scale: home, notes, durs, tag, swing, changes, noteChord, lead: lead || undefined };
}

export function L(id: string, stage: number, home: Mode, notes: number[], durs?: number[], tag?: string): Lick {
  const d = durs ?? notes.map((_, i) => (i === notes.length - 1 ? 2 : 0.5));
  if (d.length !== notes.length) throw new Error(`lick ${id}: durs length mismatch`);
  return { id, stage, home, scale: scaleFromTag(tag) ?? home, notes, durs: d, tag, swing: swingFromTag(tag) };
}

// Jazz and blues phrasing swings; folk, pop and rock phrasing stays straight.
const SWING_TAGS = /^(swing|blues|blues turn|bebop)$/i;
function swingFromTag(tag?: string): boolean {
  return !!tag && SWING_TAGS.test(tag);
}
// Progression Paths that swing: Blues Bayou, Jazz Junction, Turnaround Tower, Minor Moors, Bebop Boulevard.
const SWING_STAGES = new Set([13, 14, 15, 17, 19]);

function scaleFromTag(tag?: string): Scale | null {
  if (!tag) return null;
  if (/^dorian/i.test(tag)) return 'dorian';
  if (/^mixo/i.test(tag)) return 'mixolydian';
  if (/^lydian/i.test(tag)) return 'lydian';
  if (/^phrygian/i.test(tag)) return 'phrygian';
  return null;
}

