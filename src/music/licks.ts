import type { Mode, Scale } from './theory';

// A lick is a short phrase measured from the tonic in semitones (0 = home,
// 12 = home an octave up) with a duration in beats for each note.
export interface Lick {
  id: string;
  stage: number;
  home: Mode;
  // The exact mode, when it is more specific than major/minor.
  scale: Scale;
  notes: number[];
  durs: number[];
  tag?: string;
  // Play written eighths long-short.
  swing?: boolean;
  // Rest before the first note, in beats (a pickup). Keeps the phrase on the
  // beat against the backing, whose first chord includes this rest.
  lead?: number;
  // Harmony licks: the chord changes underneath, and which chord each note sits on.
  changes?: Chord[];
  noteChord?: number[];
}

// A chord in the changes, measured from the tonic like everything else.
// `tones` is the voicing (semis above the tonic); `root` names it.
export interface Chord {
  roman: string;
  suffix: string;
  root: number;
  tones: number[];
  beats: number;
}

type ChordShape = Omit<Chord, 'beats'>;
const c = (roman: string, suffix: string, root: number, tones: number[]): ChordShape => ({ roman, suffix, root, tones });

